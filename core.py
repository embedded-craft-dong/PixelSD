"""Offline RGB565 conversion. No configuration or source metadata stored."""
import json
import struct
import re
from pathlib import Path
from PIL import Image, ImageOps

SIZE = (240, 320)

def validate_size(size):
    if len(size) != 2 or any(type(v) is not int or not 1 <= v <= 2047 for v in size):
        raise ValueError('宽度和高度必须是 1–2047 之间的整数。')
    return tuple(size)

def prepare(path, fit='contain', size=SIZE, rotation=0, mirror='none', background='#000000'):
    size = validate_size(size)
    with Image.open(path) as source:
        source = ImageOps.exif_transpose(source).convert('RGBA')
        if rotation not in (0,90,180,270):raise ValueError('Invalid rotation')
        if rotation:source=source.rotate(-rotation,expand=True)
        if mirror in ('horizontal','both'):source=ImageOps.mirror(source)
        if mirror in ('vertical','both'):source=ImageOps.flip(source)
        backdrop = Image.new('RGBA', source.size, background)
        backdrop.alpha_composite(source)
        image = backdrop.convert('RGB')
        if fit == 'cover':
            return ImageOps.fit(image, size, method=Image.Resampling.LANCZOS)
        if fit == 'stretch':
            return image.resize(size, Image.Resampling.LANCZOS)
        image = ImageOps.contain(image, size, method=Image.Resampling.LANCZOS)
        canvas = Image.new('RGB', size, background)
        canvas.paste(image, ((size[0]-image.width)//2, (size[1]-image.height)//2))
        return canvas

def encode(image, endian='little', color='RGB'):
    data = bytearray()
    for r, g, b in image.get_flattened_data():
        if color == 'BGR':
            r, b = b, r
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data.extend(v.to_bytes(2, endian))
    return bytes(data)

def containers(pixels, size=SIZE):
    width, height = validate_size(size)
    if len(pixels) != width * height * 2:
        raise ValueError('Invalid pixel length')
    # LVGL8 little-endian bit fields: cf:5, zero:3, reserved:2, w:11, h:11.
    header = struct.pack('<I', 4 | (width << 10) | (height << 21))
    return header + pixels, b'R565' + struct.pack('<HHI', width, height, 0) + pixels

def validate_range(start, end, count):
    if not 1 <= start <= end <= 9999:
        raise ValueError('序号必须在 1–9999 之间，结束序号不能小于起始序号。')
    if end-start+1 != count:
        raise ValueError(f'已选择 {count} 张图片，序号范围需要 {end-start+1} 张。')

def write_pair(folder, number, pixels, size=SIZE):
    """Exclusive creation: never overwrite files; roll back our partial pair."""
    write_outputs(folder, number, pixels, size)

def c_array(number, pixels, size=SIZE, endian='little'):
    width, height = validate_size(size)
    if len(pixels) != width*height*2:
        raise ValueError('Invalid pixel length')
    base = f'IMG{number:04}'
    values = [f'0x{int.from_bytes(pixels[i:i+2], endian):04X}' for i in range(0,len(pixels),2)]
    lines = ['    '+', '.join(values[i:i+12])+',' for i in range(0,len(values),12)]
    text = ('/* Generated by PixelSD. 16-bit 565 pixel values, row-major. */\n'
            '/* Byte order in memory follows the target CPU; configure LCD transfer accordingly. */\n'
            f'#ifndef {base}_H\n#define {base}_H\n#include <stdint.h>\n\n'
            f'#define {base}_WIDTH {width}\n#define {base}_HEIGHT {height}\n'
            f'static const uint16_t {base}[{width*height}] = {{\n'+ '\n'.join(lines)+f'\n}};\n\n#endif /* {base}_H */\n')
    return text.encode('ascii')

def c_files(number,pixels,size=SIZE,endian='little',ctype='uint16_t',layout='header'):
    width,height=validate_size(size)
    if len(pixels)!=width*height*2:raise ValueError('Invalid pixel length')
    if ctype not in ('uint8_t','uint16_t') or layout not in ('header','split'):raise ValueError('Invalid C format')
    if ctype=='uint16_t' and layout=='header':return {'.h':c_array(number,pixels,size,endian)}
    base=f'IMG{number:04}'
    values=([f'0x{v:02X}' for v in pixels] if ctype=='uint8_t' else
            [f'0x{int.from_bytes(pixels[i:i+2],endian):04X}' for i in range(0,len(pixels),2)])
    count=len(values)
    body='\n'.join('    '+', '.join(values[i:i+12])+',' for i in range(0,count,12))
    comment='/* Generated by PixelSD. Row-major 565 pixels. */\n'
    comment+=('/* Bytes follow the selected pixel byte order. */\n' if ctype=='uint8_t' else
              '/* uint16_t values use target CPU memory order. */\n')
    header=comment+f'#ifndef {base}_H\n#define {base}_H\n#include <stdint.h>\n'
    header+=f'#define {base}_WIDTH {width}\n#define {base}_HEIGHT {height}\n'
    if layout=='header':
        return {'.h':(header+f'static const {ctype} {base}[{count}] = {{\n{body}\n}};\n#endif\n').encode('ascii')}
    declaration=f'extern const {ctype} {base}[{count}];\n'
    header+='#ifdef __cplusplus\nextern "C" {\n#endif\n'+declaration+'#ifdef __cplusplus\n}\n#endif\n#endif\n'
    definition=comment+f'#include "{base}.h"\nconst {ctype} {base}[{count}] = {{\n{body}\n}};\n'
    return {'.h':header.encode('ascii'),'.c':definition.encode('ascii')}

def output_extensions(mode,layout='header'):
    c=('.h','.c') if layout=='split' else ('.h',)
    return {'binary':('.bin','.r56'), 'c':c, 'both':('.bin','.r56')+c}[mode]

def write_outputs(folder, number, pixels, size=SIZE, mode='binary', endian='little',ctype='uint16_t',layout='header'):
    base=f'IMG{number:04}'
    files={}
    if mode in ('binary','both'):
        files.update(zip(('.bin','.r56'),containers(pixels,size)))
    if mode in ('c','both'):
        files.update(c_files(number,pixels,size,endian,ctype,layout))
    if not files:raise ValueError('Invalid output mode')
    created = []
    try:
        for ext,data in files.items():
            path=Path(folder)/(base+ext)
            with path.open('xb') as stream:
                created.append(path)
                stream.write(data)
    except Exception:
        for path in created:
            path.unlink(missing_ok=True)
        raise

def decode(pixels,size,endian='little',color='RGB'):
    width,height=validate_size(size)
    if len(pixels)!=width*height*2:raise ValueError('Invalid pixel length')
    data=bytearray(width*height*3)
    for i in range(width*height):
        v=int.from_bytes(pixels[i*2:i*2+2],endian)
        r,g,b=(v>>11)&31,(v>>5)&63,v&31
        r,g,b=(r<<3)|(r>>2),(g<<2)|(g>>4),(b<<3)|(b>>2)
        if color=='BGR':r,b=b,r
        data[i*3:i*3+3]=bytes((r,g,b))
    return Image.frombytes('RGB',size,bytes(data))

def read_binary(path,endian='little',color='RGB'):
    path=Path(path)
    if path.stat().st_size>2047*2047*2+12:raise ValueError('File too large')
    data=path.read_bytes()
    if path.suffix.lower()=='.r56':
        if len(data)<12 or data[:4]!=b'R565':raise ValueError('Invalid R56 header')
        width,height,flags=struct.unpack('<HHI',data[4:12])
        if flags:raise ValueError('Unsupported R56 flags')
        offset=12;kind='R565'
    elif path.suffix.lower()=='.bin':
        if len(data)<4:raise ValueError('Invalid BIN header')
        header=int.from_bytes(data[:4],'little')
        if header&1023!=4:raise ValueError('Unsupported LVGL8 format')
        width,height=(header>>10)&2047,header>>21
        offset=4;kind='LVGL8 TRUE_COLOR / RGB565'
    else:raise ValueError('Expected .bin or .r56')
    size=validate_size((width,height))
    image=decode(data[offset:],size,endian,color)
    return image,{'width':width,'height':height,'bytes':len(data),'header_bytes':offset,'format':kind}

def natural_key(path):
    return tuple((1,int(part)) if part.isdigit() else (0,part.casefold()) for part in re.split(r'(\d+)',Path(path).name))

IMAGE_EXTENSIONS={'.jpg','.jpeg','.png','.bmp','.webp','.tif','.tiff'}

def collect_images(paths):
    result=[];seen=set()
    for value in paths:
        p=Path(value)
        candidates=sorted(p.iterdir(),key=natural_key) if p.is_dir() else [p]
        for item in candidates:
            key=str(item.resolve()).casefold()
            if item.is_file() and item.suffix.lower() in IMAGE_EXTENSIONS and key not in seen:
                result.append(str(item.resolve()));seen.add(key)
    return result

def write_index(folder, numbers, fit, size=SIZE):
    # A batch-specific manifest cannot accidentally replace an SD card's full index.
    width, height = validate_size(size)
    data = {'format': 'LVGL8 RGB565 LE', 'width': width, 'height': height, 'fit': fit,
            'images': [{'file': f'IMG{n:04}.bin', 'bytes': width*height*2+4} for n in numbers]}
    path = Path(folder)/f'INDEX_{numbers[0]:04}_{numbers[-1]:04}.JSON'
    with path.open('x', encoding='utf-8') as stream:
        json.dump(data, stream, ensure_ascii=False, indent=2)
